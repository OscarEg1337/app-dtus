-- migracion_catalogo_ubicaciones.sql — catálogo real de CC / Manzana / Lote
-- por Fraccionamiento (fuente: FRACCIONAMIENTOS.xlsx hoja FRACC), para que
-- Nueva Solicitud use listas desplegables en cascada (Fraccionamiento → CC
-- → Manzana → Lote) en vez de texto libre. Etapa se queda como texto libre.
-- Correr UNA VEZ en el SQL Editor de Supabase.
--
-- Nota: los nombres "PUERTA JARDIN" y "PUERTA JARDIN PLUS" del Excel se
-- normalizaron a "PUERTA JARDÍN" / "PUERTA JARDÍN PLUS" para que coincidan
-- exactamente con FRACCIONAMIENTOS_SEED (js/seed/fraccionamientos.seed.js).
-- El catálogo también trae 4 fraccionamientos que HOY NO existen en la app
-- (FUENTES DE JUAREZ, LYSARA, PH LINCES II, PILARES ANTARES) — se insertan
-- de todos modos por si se agregan después, pero no van a aparecer en el
-- dropdown de Nueva Solicitud hasta que se den de alta ahí también.

create table if not exists public.catalogo_ubicaciones (
  id bigint generated always as identity primary key,
  fraccionamiento text not null,
  cc text not null,
  manzana text not null,
  lote text not null
);

create index if not exists idx_catalogo_ubicaciones_fraccionamiento
  on public.catalogo_ubicaciones (fraccionamiento);

alter table public.catalogo_ubicaciones enable row level security;

drop policy if exists "cualquier usuario logueado lee el catalogo" on public.catalogo_ubicaciones;
create policy "cualquier usuario logueado lee el catalogo"
  on public.catalogo_ubicaciones for select
  using (auth.uid() is not null);

-- Vacía la tabla antes de insertar, para que este script se pueda volver a
-- correr sin duplicar filas si algún día se actualiza el catálogo completo.
